CREATE TABLE hotels (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL
);

CREATE TABLE rooms (
                       id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       hotel_id INTEGER NOT NULL,
                       room_number INTEGER NOT NULL,
                       type VARCHAR(20) NOT NULL,

                       CONSTRAINT uq_rooms_hotel_room_number
                           UNIQUE (hotel_id, room_number),

                       CONSTRAINT fk_rooms_hotel
                           FOREIGN KEY (hotel_id)
                               REFERENCES hotels(id)
                               ON DELETE RESTRICT,

                       CONSTRAINT ck_rooms_type
                           CHECK (type IN ('SINGLE', 'DOUBLE', 'DELUXE'))
);

CREATE TABLE bookings (
                          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          check_in DATE NOT NULL,
                          check_out DATE NOT NULL,
                          created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                          number_of_guests INTEGER NOT NULL,
                          reference VARCHAR(8) NOT NULL,
                          room_id INTEGER NOT NULL,

                          CONSTRAINT uq_bookings_reference
                              UNIQUE (reference),

                          CONSTRAINT ck_bookings_dates
                              CHECK (check_out > check_in),

                          CONSTRAINT ck_bookings_guests
                              CHECK (number_of_guests > 0),

                          CONSTRAINT fk_bookings_room
                              FOREIGN KEY (room_id)
                                  REFERENCES rooms(id)
                                  ON DELETE RESTRICT
);

CREATE INDEX ix_bookings_room_id ON bookings(room_id);